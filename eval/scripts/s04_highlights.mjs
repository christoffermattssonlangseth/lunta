// Step 4: highlight survival across reading-view versions.
//
// For every paper, 20 simulated highlights (passages of 5-40 words inside body paragraphs) are drawn
// from a source reading view, stored the way the reader stores them (quote, 40 characters of prefix
// and suffix, start offset in the page text: see luntaSelection in apple/Shared/Highlights.swift),
// and re-anchored in a target reading view with the reader's own `locate` function, which is read
// out of apple/Shared/Highlights.swift at run time (not copied), so the test follows the app.
//
// Scenarios (source -> target):
//   swift -> xml   highlight made on today's PDF reading view; the paper is later rebuilt from its XML
//   base  -> xml   the same for a highlight made on the old (pre-fix) PDF reading view
//   rust  -> xml   the same for the Rust converter (Android, Windows/Linux)
//   base  -> swift old highlight; the PDF reading view is regenerated by today's converter
//
// Each highlight is classified by the first tier of `locate` that finds it: exact (quote found
// verbatim), whitespace (found ignoring whitespace), fold (found ignoring spacing, quote marks,
// dashes and case, whole quote or its first 100 characters), startend (only its longest surviving
// start and end are found), lost. A located span counts as correct when at least half of the
// quote's words appear, in order, in the text it was anchored to.
//
// Usage: node s04_highlights.mjs  (reads results/corpus.csv and data/out; writes
// results/highlights.csv and data/highlights.jsonl)
//        node s04_highlights.mjs --scenarios swift:page-swift,rust:page-rust --out highlights_pages
// (other scenarios, e.g. the journal-page reading views of s06; writes results/<out>.csv and
// data/<out>.jsonl; papers without both views are skipped)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const EVAL = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(EVAL, '..');
const OUT = path.join(EVAL, 'data', 'out');
const N_PER_PAPER = 20;
const argv = process.argv.slice(2);
const opt = k => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : null; };
const SCENARIOS = opt('--scenarios') ? opt('--scenarios').split(',').map(x => x.split(':'))
  : [['swift', 'xml'], ['base', 'xml'], ['rust', 'xml'], ['base', 'swift']];
const OUTNAME = opt('--out') || 'highlights';

// ------------------------------------------------------------------ the app's locate()
const swiftSrc = fs.readFileSync(path.join(REPO, 'apple/Shared/Highlights.swift'), 'utf8');
const a0 = swiftSrc.indexOf('var lcache = { text: null };');
const a1 = swiftSrc.indexOf('function wrap(', a0);
if (a0 < 0 || a1 < 0) throw new Error('locate() not found in Highlights.swift');
const locateSrc = swiftSrc.slice(a0, a1);
// (base(): where a chapter's text starts in the whole view's text; 0 for a paper, as here)
const locate = new Function('function base(){ return 0; }\n' + locateSrc + '\nreturn locate;')();

// ------------------------------------------------------------------ reading-view text
const ENT = { lt: '<', gt: '>', amp: '&', quot: '"', apos: "'", nbsp: ' ' };
const decode = s => s.replace(/&(#x[0-9a-f]+|#\d+|\w+);/gi, (m, e) => {
  if (e[0] === '#') return String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
  return ENT[e] ?? m;
});
const VOID = new Set(['img', 'br', 'hr', 'meta', 'link', 'input', 'col', 'source', 'wbr']);
const REF_HEAD = /^\s*(\d+\.?\s*)?(references?( and notes)?|bibliography|literature cited|works cited|reference list|citations?)\s*$/i;

function spine(dir) {
  const root = path.join(dir, 'EPUB');
  const opf = fs.readFileSync(path.join(root, 'content.opf'), 'utf8');
  const items = {};
  for (const m of opf.matchAll(/<item\s[^>]*?id="([^"]+)"[^>]*?href="([^"]+)"/g)) items[m[1]] = m[2];
  return [...opf.matchAll(/<itemref\s[^>]*idref="([^"]+)"/g)].map(m => path.join(root, items[m[1]]));
}

// The page text (body textContent of the chapters, in order) and the body paragraphs in it.
function readingView(dir) {
  let text = '';
  const paras = [];
  for (const f of spine(dir)) {
    const base = path.basename(f);
    if (base === 'cover.xhtml' || base === 'nav.xhtml') continue;
    const html = fs.readFileSync(f, 'utf8');
    const b0 = html.search(/<body[^>]*>/);
    const body = html.slice(html.indexOf('>', b0) + 1, html.lastIndexOf('</body>'));
    const stack = [];
    let pStart = -1, skipDepth = 0, inRefs = false, headText = null;
    for (const m of body.matchAll(/<[^>]+>|[^<]+/g)) {
      const tok = m[0];
      if (tok[0] !== '<') {
        const t = decode(tok);
        if (headText !== null) headText += t;
        text += t;
        continue;
      }
      const end = tok.match(/^<\/(\w+)/);
      if (end) {
        const name = end[1].toLowerCase();
        while (stack.length) {
          const top = stack.pop();
          if (top.skip) skipDepth--;
          if (top.name === 'p' && top.para && pStart >= 0) { paras.push([pStart, text.length]); pStart = -1; }
          if (/^h[1-6]$/.test(top.name) && headText !== null) { inRefs = REF_HEAD.test(headText); headText = null; }
          if (top.name === name) break;
        }
        continue;
      }
      const st = tok.match(/^<(\w+)([^>]*?)(\/?)>$/);
      if (!st) continue;
      const name = st[1].toLowerCase(), attrs = st[2];
      if (st[3] === '/' || VOID.has(name)) continue;
      const cls = (attrs.match(/class="([^"]*)"/) || [, ''])[1].split(/\s+/);
      const skip = name === 'figure' || (name === 'div' && (cls.includes('table-wrap') || cls.includes('equation'))) ||
        (name === 'section' && (cls.includes('titlepage') || cls.includes('references'))) || cls.includes('caption') ||
        name === 'table' || (name === 'ol' && cls.includes('refs'));
      const para = name === 'p' && !attrs.includes('class=') && skipDepth === 0 && !skip && !inRefs;
      if (skip) skipDepth++;
      if (/^h[1-6]$/.test(name)) headText = '';
      stack.push({ name, skip, para });
      if (para) pStart = text.length;
    }
  }
  return { text, paras };
}

// ------------------------------------------------------------------ sampling
function mulberry32(a) {
  return function () { a |= 0; a = a + 0x6D2B79F5 | 0; let t = Math.imul(a ^ a >>> 15, 1 | a); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
}
function hash(s) { let h = 2166136261; for (const c of s) { h ^= c.codePointAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }

function sample(view, seedStr) {
  const rnd = mulberry32(hash(seedStr));
  const cands = [];
  for (const [s, e] of view.paras) {
    const words = [...view.text.slice(s, e).matchAll(/\S+/g)].map(m => [s + m.index, s + m.index + m[0].length]);
    if (words.length >= 8) cands.push(words);
  }
  if (!cands.length) return [];
  const total = cands.reduce((n, w) => n + w.length, 0);
  const out = [];
  for (let k = 0; k < N_PER_PAPER; k++) {
    let r = rnd() * total, words = cands[0];
    for (const w of cands) { if (r < w.length) { words = w; break; } r -= w.length; }
    const L = 5 + Math.floor(rnd() * (Math.min(40, words.length) - 4));
    const i = Math.floor(rnd() * (words.length - L + 1));
    const s = words[i][0], e = words[i + L - 1][1];
    out.push({ quote: view.text.slice(s, e), prefix: view.text.slice(Math.max(0, s - 40), s), suffix: view.text.slice(e, e + 40), start: s, words: L });
  }
  return out;
}

// ------------------------------------------------------------------ tiers
const squash = s => s.replace(/\s+/g, ' ');
const SKIP = /[\s'"‘’‚‛“”„‟´`«»]/;
function foldc(c) {
  if (c === 'µ') return 'μ';
  if (/[‘’]/.test(c)) return "'";
  if (/[“”]/.test(c)) return '"';
  if (/[‐-—−]/.test(c)) return '-';
  return c.toLowerCase();
}
const denseOf = s => { let d = ''; for (const c of s) if (!SKIP.test(c)) d += foldc(c); return d; };

function tier(text, dense, flat, h) {
  if (text.indexOf(h.quote) >= 0) return 'exact';
  if (flat.indexOf(squash(h.quote).trim()) >= 0) return 'whitespace';
  const dq = denseOf(h.quote);
  if (dense.indexOf(dq) >= 0 || (dq.length > 140 && dense.indexOf(dq.slice(0, 100)) >= 0)) return 'fold';
  return 'startend';
}

const words = s => (s.toLowerCase().match(/[\p{L}\p{N}]+/gu) || []);
function lcsRatio(q, t) {
  const a = words(q), b = words(t);
  if (!a.length) return 0;
  let prev = new Array(b.length + 1).fill(0);
  for (let i = 1; i <= a.length; i++) {
    const cur = new Array(b.length + 1).fill(0);
    for (let j = 1; j <= b.length; j++) cur[j] = a[i - 1] === b[j - 1] ? prev[j - 1] + 1 : Math.max(prev[j], cur[j - 1]);
    prev = cur;
  }
  return prev[b.length] / a.length;
}

// ------------------------------------------------------------------ main
const corpus = fs.readFileSync(path.join(EVAL, 'results/corpus.csv'), 'utf8').trim().split('\n');
const head = corpus[0].split(',');
const rows = corpus.slice(1).map(l => { const v = l.split(','); return { pmcid: v[head.indexOf('pmcid')], group: v[head.indexOf('group')] }; });
const okDir = (sys, id) => {
  const r = path.join(OUT, sys, id, 'run.json');
  return fs.existsSync(r) && JSON.parse(fs.readFileSync(r, 'utf8')).ok ? path.join(OUT, sys, id, 'epub') : null;
};
const csv = ['pmcid,group,source,target,n,exact,whitespace,fold,startend,lost,correct,misplaced'];
const jl = fs.openSync(path.join(EVAL, `data/${OUTNAME}.jsonl`), 'w');
const cache = new Map();
const view = (sys, id) => { const k = sys + '/' + id; if (!cache.has(k)) cache.set(k, readingView(okDir(sys, id))); return cache.get(k); };
for (const { pmcid, group } of rows) {
  cache.clear();
  for (const [src, dst] of SCENARIOS) {
    if (!okDir(src, pmcid) || !okDir(dst, pmcid)) continue;
    const hs = sample(view(src, pmcid), pmcid + ':' + src);
    const target = view(dst, pmcid).text;
    let flat = '', dense = '';
    for (let k = 0; k < target.length; k++) { const c = target[k]; if (/\s/.test(c)) { if (flat.length && flat[flat.length - 1] === ' ') continue; flat += ' '; } else flat += c; }
    dense = denseOf(target);
    const n = { exact: 0, whitespace: 0, fold: 0, startend: 0, lost: 0, correct: 0, misplaced: 0 };
    for (const h of hs) {
      const at = locate(target, h);
      let t = 'lost', ok = false;
      if (at) {
        t = tier(target, dense, flat, h);
        ok = lcsRatio(h.quote, target.slice(at[0], at[1])) >= 0.5;
        n[ok ? 'correct' : 'misplaced']++;
      }
      n[t]++;
      fs.writeSync(jl, JSON.stringify({ pmcid, source: src, target: dst, tier: t, correct: ok, words: h.words, quote: h.quote, found: at ? target.slice(at[0], at[1]) : null }) + '\n');
    }
    csv.push([pmcid, group, src, dst, hs.length, n.exact, n.whitespace, n.fold, n.startend, n.lost, n.correct, n.misplaced].join(','));
  }
}
fs.closeSync(jl);
fs.writeFileSync(path.join(EVAL, `results/${OUTNAME}.csv`), csv.join('\n') + '\n');
console.error(`wrote ${csv.length - 1} rows`);
